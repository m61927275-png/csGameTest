// Helper functions
export function getWeaponsByType(type) {
    return Object.values(WEAPONS).filter(w => w.type === type);
}

export function getWeaponsByTeam(team) {
    return Object.values(WEAPONS).filter(w => w.team === team || w.team === 'both');
}

export function getWeaponsBySlot(slot) {
    return Object.values(WEAPONS).filter(w => w.slot === slot);
}

export function getBuyMenuCategories() {
    return {
        pistols: getWeaponsByType(WEAPON_TYPES.PISTOL),
        smgs: getWeaponsByType(WEAPON_TYPES.SMG),
        rifles: [...getWeaponsByType(WEAPON_TYPES.RIFLE), ...getWeaponsByType(WEAPON_TYPES.SNIPER)],
        heavy: [...getWeaponsByType(WEAPON_TYPES.SHOTGUN), ...getWeaponsByType(WEAPON_TYPES.MACHINEGUN)],
        grenades: getWeaponsByType(WEAPON_TYPES.GRENADE),
        equipment: getWeaponsByType(WEAPON_TYPES.EQUIPMENT)
    };
}

